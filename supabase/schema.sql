-- Customers create orders through place_order() below, never directly.
drop policy if exists "admins manage orders" on public.orders;
create policy "admins manage orders" on public.orders
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admins manage order items" on public.order_items;
create policy "admins manage order items" on public.order_items
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admins can see admins" on public.admins;
create policy "admins can see admins" on public.admins
  for select to authenticated using (user_id = auth.uid());

-- ------------------------------------------------------------- functions

create or replace function public.holds_stock(s text)
returns boolean language sql immutable as $$
  select s in ('confirmed','paid','collected');
$$;

-- Creates an order. Prices always come from the products table, never from
-- the browser. Customers (anon) can only create "new" orders, which do not
-- touch stock. Admins can create an order in any status.
create or replace function public.place_order(
  p_customer text,
  p_phone    text,
  p_pickup   text,
  p_note     text,
  p_items    jsonb,
  p_status   text default 'new'
) returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_id     text := gen_random_uuid()::text;
  v_number integer;
  v_total  integer := 0;
  v_item   jsonb;
  v_prod   public.products%rowtype;
  v_qty    integer;
  v_deduct boolean := public.holds_stock(p_status);
begin
  if p_status <> 'new' and not public.is_admin() then
    raise exception 'Not allowed';
  end if;
  if jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0
     or jsonb_array_length(p_items) > 30 then
    raise exception 'Invalid items';
  end if;

  insert into public.orders (id, customer, phone, pickup, note, status, stock_deducted)
  values (
    v_id,
    left(coalesce(nullif(trim(p_customer), ''), 'WhatsApp customer'), 120),
    left(coalesce(p_phone, ''), 40),
    left(coalesce(p_pickup, ''), 60),
    left(coalesce(p_note, ''), 500),
    p_status,
    v_deduct
  )
  returning number into v_number;

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'qty')::integer;
    if v_qty is null or v_qty < 1 or v_qty > 99 then
      raise exception 'Invalid quantity';
    end if;
    select * into v_prod from public.products
      where id = v_item->>'product_id' for update;
    if not found then
      raise exception 'Unknown product';
    end if;
    if v_deduct then
      if v_prod.stock < v_qty then
        raise exception 'Not enough stock for %', v_prod.name;
      end if;
      update public.products set stock = stock - v_qty where id = v_prod.id;
    end if;
    insert into public.order_items (order_id, product_id, name, size, price, qty)
    values (v_id, v_prod.id, v_prod.name, v_prod.size, v_prod.price, v_qty);
    v_total := v_total + v_prod.price * v_qty;
  end loop;

  update public.orders set total = v_total where id = v_id;
  return v_number;
end;
$$;

-- Moves an order to a new status and keeps stock in step.
create or replace function public.set_order_status(p_id text, p_status text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_item  public.order_items%rowtype;
begin
  if not public.is_admin() then raise exception 'Not allowed'; end if;
  select * into v_order from public.orders where id = p_id for update;
  if not found or v_order.status = p_status then return; end if;

  if public.holds_stock(p_status) and not v_order.stock_deducted then
    for v_item in select * from public.order_items where order_id = p_id loop
      update public.products set stock = greatest(0, stock - v_item.qty)
        where id = v_item.product_id;
    end loop;
    update public.orders set stock_deducted = true where id = p_id;
  elsif not public.holds_stock(p_status) and v_order.stock_deducted then
    for v_item in select * from public.order_items where order_id = p_id loop
      update public.products set stock = stock + v_item.qty
        where id = v_item.product_id;
    end loop;
    update public.orders set stock_deducted = false where id = p_id;
  end if;
  update public.orders set status = p_status where id = p_id;
end;
$$;

create or replace function public.delete_order(p_id text)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_item  public.order_items%rowtype;
begin
  if not public.is_admin() then raise exception 'Not allowed'; end if;
  select * into v_order from public.orders where id = p_id for update;
  if not found then return; end if;
  if v_order.stock_deducted then
    for v_item in select * from public.order_items where order_id = p_id loop
      update public.products set stock = stock + v_item.qty
        where id = v_item.product_id;
    end loop;
  end if;
  delete from public.orders where id = p_id;
end;
$$;

create or replace function public.adjust_stock(p_id text, p_delta integer)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then raise exception 'Not allowed'; end if;
  update public.products set stock = greatest(0, stock + p_delta) where id = p_id;
end;
$$;

