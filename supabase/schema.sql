-- Doxa Naturals: database schema.
-- Run this whole file once in the Supabase dashboard (SQL Editor > New query).
-- It is safe to re-run: every statement is idempotent.

-- ---------------------------------------------------------------- tables

create table if not exists public.products (
  id          text primary key default gen_random_uuid()::text,
  name        text not null,
  size        text not null default '',
  price       integer not null check (price >= 0),
  description text not null default '',
  image       text not null default '',
  stock       integer not null default 0 check (stock >= 0),
  position    integer generated by default as identity,
  created_at  timestamptz not null default now()
);

create table if not exists public.orders (
  id             text primary key default gen_random_uuid()::text,
  number         integer generated by default as identity (start with 1001),
  created_at     timestamptz not null default now(),
  customer       text not null default '',
  phone          text not null default '',
  pickup         text not null default '',
  note           text not null default '',
  status         text not null default 'new'
                 check (status in ('new','confirmed','paid','collected','cancelled')),
  total          integer not null default 0,
  stock_deducted boolean not null default false
);

create table if not exists public.order_items (
  id         bigint generated by default as identity primary key,
  order_id   text not null references public.orders(id) on delete cascade,
  product_id text not null,
  name       text not null,
  size       text not null default '',
  price      integer not null,
  qty        integer not null check (qty > 0)
);
create index if not exists order_items_order_idx on public.order_items(order_id);

-- Who may use the admin dashboard. Add yourself after creating your user
-- (see the bottom of this file).
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

